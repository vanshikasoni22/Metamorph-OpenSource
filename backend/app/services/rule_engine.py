"""
================================================================================
PLACEHOLDER HOOK: Contrib Rule Engine
================================================================================
Future integration points:
1. Hard Blockers: CI failures, merge conflicts, breaking changes, scope violations.
2. Explicit Scoring: Calculating test coverage, diff cleanliness, author responsiveness.
3. Evidence Validation: Verifying that cited file and line references actually exist in diffs.

Currently returns deterministic placeholder scores and verdicts derived from fetched PR data
so the maintainer review results screen works end-to-end.
"""

import logging
from typing import List, Dict, Any
from ..models import (
    PRData,
    ScoredPR,
    VerdictClaim,
    ScoreResponse,
    MaintainerFetchResponse
)

logger = logging.getLogger("contribo.rule_engine")

def evaluate_pr_rules_placeholder(pr: PRData, rank: int) -> ScoredPR:
    """
    Placeholder scoring rule implementation.
    Evaluates basic signals from the real PR (CI status, changed files, test presence).
    """
    verdicts: List[VerdictClaim] = []
    base_score = 90 - (rank - 1) * 12

    # Check for tests in changed files
    test_files = [f for f in pr.files if "test" in f.filename.lower()]
    if test_files:
        verdicts.append(
            VerdictClaim(
                status="supported",
                claim="Adds or updates test coverage",
                evidence=f"{test_files[0].filename} ({test_files[0].additions} additions)"
            )
        )
    else:
        verdicts.append(
            VerdictClaim(
                status="unknown",
                claim="Test coverage verification",
                evidence="No files matching 'test' detected in PR diff. Needs human review."
            )
        )

    # Check module scope
    if pr.files:
        total_files = len(pr.files)
        verdicts.append(
            VerdictClaim(
                status="supported",
                claim="Diff scope bounded",
                evidence=f"{total_files} file(s) changed (+{pr.additions} / -{pr.deletions})"
            )
        )

    # Check CI status
    if pr.ci_status.state == "failure":
        base_score = max(10, base_score - 30)
        failing_checks = [c.name for c in pr.ci_status.check_runs if c.conclusion in ("failure", "timed_out")]
        check_name = failing_checks[0] if failing_checks else "CI Check"
        verdicts.append(
            VerdictClaim(
                status="blocker",
                claim=f"Required check '{check_name}' is failing",
                evidence=f"check_run/{check_name} · conclusion: failure"
            )
        )
    elif pr.ci_status.state == "success":
        verdicts.append(
            VerdictClaim(
                status="supported",
                claim="All CI checks passed",
                evidence=f"{pr.ci_status.total_checks} checks passed cleanly"
            )
        )
    else:
        verdicts.append(
            VerdictClaim(
                status="unknown",
                claim="CI status verification",
                evidence="Check runs status is pending or not reported."
            )
        )

    # Backward compatibility / breaking change check placeholder
    verdicts.append(
        VerdictClaim(
            status="unknown",
            claim="Stays backward compatible",
            evidence="Placeholder verdict: Rule engine LLM verification hook pending."
        )
    )

    final_score = max(5, min(99, base_score))

    return ScoredPR(
        rank=rank,
        pr_number=pr.number,
        title=pr.title,
        author=pr.author or "unknown",
        score=final_score,
        verdicts=verdicts,
        files=pr.files,
        raw_pr=pr
    )

def generate_review_markdown(issue_title: str, scored_prs: List[ScoredPR]) -> str:
    lines = [f"## Contrib Evidence Review: {issue_title}", ""]
    for pr in scored_prs:
        lines.append(f"### Rank #{pr.rank}: PR #{pr.pr_number} — {pr.title} (Score: {pr.score}/100)")
        lines.append(f"**Author:** @{pr.author}")
        for v in pr.verdicts:
            icon = "✓" if v.status == "supported" else ("✕" if v.status == "blocker" else "?")
            lines.append(f"- **{icon} [{v.status.upper()}]** {v.claim}: `{v.evidence}`")
        lines.append("")
    lines.append("*Automated report generated by Contrib evidence engine. Human maintainer review required before merge.*")
    return "\n".join(lines)

def run_placeholder_scoring(fetch_response: MaintainerFetchResponse) -> ScoreResponse:
    """
    Main placeholder scoring hook entry point.
    """
    scored = []
    # Rank PRs: sort by fewest errors first, then additions/tests
    sorted_prs = sorted(
        fetch_response.pull_requests,
        key=lambda p: (1 if p.error else 0, 1 if p.ci_status.state == "failure" else 0)
    )

    for idx, pr in enumerate(sorted_prs, start=1):
        scored.append(evaluate_pr_rules_placeholder(pr, rank=idx))

    summary_md = generate_review_markdown(fetch_response.issue.title, scored)

    return ScoreResponse(
        issue_title=fetch_response.issue.title,
        issue_number=fetch_response.issue.number,
        candidate_prs=scored,
        summary_markdown=summary_md
    )
